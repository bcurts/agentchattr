    function normalizeLang(value) {
        if (value === 'zh-CN' || value === 'zhCN' || value === 'zh') return 'zh-CN';
        if (value === 'en') return 'en';
        return 'auto';
    }

    function resolveLanguage(pref) {
        const normalized = normalizeLang(pref);
        if (normalized === 'zh-CN' || normalized === 'en') return normalized;
        const nav = (navigator.languages && navigator.languages[0]) || navigator.language || '';
        return /^zh\b/i.test(nav) ? 'zh-CN' : 'en';
    }

    function getLanguagePreference() {
        return normalizeLang(localStorage.getItem(STORAGE_KEY) || 'auto');
    }

    function getLanguage() {
        return resolveLanguage(getLanguagePreference());
    }

    function interpolate(str, vars) {
        if (!vars) return str;
        return str.replace(/\{(\w+)\}/g, (m, key) =>
            Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key]) : m
        );
    }

    function t(key, vars) {
        const lang = getLanguage();
        const table = lang === 'zh-CN' ? I18N_STRINGS.zhCN : I18N_STRINGS.en;
        const fallback = I18N_STRINGS.en;
        return interpolate(table[key] || fallback[key] || key, vars);
    }

    function applyTranslations(root) {
        const scope = root || document;
        document.documentElement.lang = getLanguage();

        scope.querySelectorAll('[data-i18n]').forEach(el => {
            el.textContent = t(el.dataset.i18n);
        });
        scope.querySelectorAll('[data-i18n-html]').forEach(el => {
            el.innerHTML = t(el.dataset.i18nHtml);
        });
        scope.querySelectorAll('[data-i18n-title]').forEach(el => {
            el.title = t(el.dataset.i18nTitle);
        });
        scope.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            el.placeholder = t(el.dataset.i18nPlaceholder);
        });
        scope.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
            el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel));
        });

        const selector = document.getElementById('setting-language');
        if (selector) selector.value = getLanguagePreference();
    }

    function setLanguage(lang) {
        const pref = normalizeLang(lang);
        localStorage.setItem(STORAGE_KEY, pref);
        applyTranslations(document);
        document.dispatchEvent(new CustomEvent('i18n:change', {
            detail: { language: getLanguage(), preference: pref },
        }));
        // Existing messages and sidebar cards are rendered HTML. Reloading keeps
        // the switch reliable without introducing a client-side virtual DOM.
        setTimeout(() => window.location.reload(), 50);
    }

    window.I18N_STRINGS = I18N_STRINGS;
    window.t = t;
    window.setLanguage = setLanguage;
    window.getLanguage = getLanguage;
    window.getLanguagePreference = getLanguagePreference;
    window.applyTranslations = applyTranslations;

    document.addEventListener('DOMContentLoaded', () => {
        applyTranslations(document);
        const selector = document.getElementById('setting-language');
        if (selector) selector.addEventListener('change', () => setLanguage(selector.value));
    });
